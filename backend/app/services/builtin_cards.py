from __future__ import annotations

from typing import Any


def _card(
    name: str,
    *,
    description: str,
    personality: str,
    scenario: str,
    first_mes: str,
    mes_example: str,
    tags: list[str],
    greetings: list[str],
    worldbook_ids: list[str],
) -> dict[str, Any]:
    return {
        "spec": "rpg_card",
        "spec_version": "1.0",
        "data": {
            "name": name,
            "description": description,
            "personality": personality,
            "scenario": scenario,
            "first_mes": first_mes,
            "mes_example": mes_example,
            "creator_notes": "首启向导内置示例，可直接改写成你自己的角色。",
            "tags": tags,
            "creator": "提线内置",
            "character_version": "1.0",
            "alternate_greetings": greetings,
            "extensions": {
                "rpg": {
                    "owner_id": "local",
                    "visibility": "private",
                    "default_worldbook_ids": list(worldbook_ids),
                }
            },
        },
        "extensions": {"rpg": {"builtin_sample": True}},
    }


